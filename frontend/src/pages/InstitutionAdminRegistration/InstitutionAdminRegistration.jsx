import React, { useCallback, useEffect, useState } from "react";
import { FiCopy, FiKey } from "react-icons/fi";
import { getMyInstitution } from "../../api/institutionApi";
import { createRegistrationCode, listRegistrationCodes, revokeRegistrationCode } from "../../api/registrationCodeApi";
import ConfirmDialog from "../../components/ConfirmDialog/ConfirmDialog";
import "../PlatformAdminAccounts.css";
import "../InstitutionLifecycle.css";

const fmt = (d) => (d ? new Date(d).toLocaleString() : "—");

// Vice Chancellor workspace. The institution is never sent: the server derives it from the signed-in account.
export default function InstitutionAdminRegistration() {
  const [institution, setInstitution] = useState(null);
  const [codes, setCodes] = useState([]);
  const [statusFilter, setStatusFilter] = useState("");
  const [fresh, setFresh] = useState(null);
  const [expiresInDays, setExpiresInDays] = useState(7);
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState("");
  const [message, setMessage] = useState("");
  const [revoking, setRevoking] = useState(null);
  const [revokeBusy, setRevokeBusy] = useState(false);

  const load = useCallback(async () => {
    try {
      const [inst, list] = await Promise.all([getMyInstitution(), listRegistrationCodes({ codeType: "institution_admin", ...(statusFilter ? { status: statusFilter } : {}) })]);
      setInstitution(inst); setCodes(Array.isArray(list) ? list : []);
    } catch (e) { setError(e.response?.data?.message || "Could not load registration data."); }
  }, [statusFilter]);
  useEffect(() => { load(); }, [load]);

  const generate = async () => {
    if (busy) return;
    setBusy(true); setError(""); setMessage(""); setFresh(null);
    try { const result = await createRegistrationCode({ codeType: "institution_admin", expiresInDays: Number(expiresInDays) || 7 }); setFresh(result); setMessage("Registration code generated."); await load(); }
    catch (e) { setError(e.response?.data?.message || "Code could not be generated."); }
    finally { setBusy(false); }
  };
  const copy = async () => {
    try { await navigator.clipboard.writeText(fresh.code); setMessage("Code copied to clipboard."); }
    catch { setError("Copy failed. Select the code and copy it manually."); }
  };
  const confirmRevoke = async () => {
    if (revokeBusy) return;
    setRevokeBusy(true);
    try { await revokeRegistrationCode(revoking._id); setRevoking(null); setMessage("Registration code revoked."); await load(); }
    catch (e) { setError(e.response?.data?.message || "Code could not be revoked."); setRevoking(null); }
    finally { setRevokeBusy(false); }
  };

  return <main className="pa-page">
    <section className="pa-hero"><span>VICE CHANCELLOR · INSTITUTION ADMIN REGISTRATION</span><h1>Institution Admin Registration</h1><p>Generate single-use codes that let your Institution Admin register for {institution?.name || "your institution"}. Codes are bound to your institution and to the Institution Admin role, expire automatically, and are shown only once.</p></section>
    {message && <div className="pa-message" role="status">{message}</div>}{error && <div className="pa-error" role="alert">{error}</div>}
    <section className="pa-grid">
      <div>
        <section className="pa-card"><div className="pa-kicker">OWN INSTITUTION</div><h2>{institution?.name || "Loading…"}</h2>
          {institution && <dl className="cd-facts"><dt>Institution ID</dt><dd>{institution._id}</dd><dt>Code</dt><dd>{institution.code}</dd><dt>Type</dt><dd>{institution.type}</dd><dt>Status</dt><dd>{institution.status}</dd></dl>}
        </section>
        <section className="pa-card" style={{ marginTop: 18 }}><div className="pa-kicker">GENERATE</div><h2>New registration code</h2>
          <label>Expires in days<input type="number" min="1" max="30" value={expiresInDays} onChange={(e) => setExpiresInDays(e.target.value)} disabled={busy} /></label>
          <button className="pa-primary" onClick={generate} disabled={busy}><FiKey aria-hidden="true" /> {busy ? "Generating…" : "Generate Institution Admin Registration Code"}</button>
        </section>
        {fresh && <section className="pa-card" style={{ marginTop: 18 }}><div className="pa-kicker">COPY NOW · SHOWN ONCE</div>
          <div className="il-code" data-testid="generated-code">{fresh.code}</div>
          <button className="il-link" onClick={copy}><FiCopy aria-hidden="true" /> Copy code</button>
          <dl className="cd-facts"><dt>Institution</dt><dd>{fresh.institution?.name}</dd><dt>Institution ID</dt><dd>{fresh.institution?._id}</dd><dt>Intended role</dt><dd>Institution Admin</dd><dt>Generated by</dt><dd>Vice Chancellor</dd><dt>Created</dt><dd>{fmt(fresh.createdAt)}</dd><dt>Expires</dt><dd>{fmt(fresh.expiresAt)}</dd><dt>Status</dt><dd>{fresh.status} · unused</dd></dl>
          <p className="pa-muted">The plaintext code is not stored and cannot be shown again. If it is lost, revoke it and generate a new one.</p></section>}
      </div>
      <section className="pa-card"><div className="pa-list-head"><div><div className="pa-kicker">CODE HISTORY</div><h2>Your institution’s codes</h2></div><span>{codes.length}</span></div>
        <div className="il-toolbar"><select aria-label="Filter by status" value={statusFilter} onChange={(e) => setStatusFilter(e.target.value)}><option value="">All</option><option value="active">Active</option><option value="used">Used</option><option value="expired">Expired</option><option value="revoked">Revoked</option></select></div>
        {codes.length === 0 ? <div className="pa-empty"><strong>No codes yet.</strong><span>Generate a code to invite your Institution Admin.</span></div> :
          <div className="il-table-wrap"><table className="il-table"><thead><tr><th>Code</th><th>Status</th><th>Generated</th><th>Expires</th><th>Used by</th><th /></tr></thead><tbody>
            {codes.map((c) => <tr key={c._id}><td>{c.codePrefix}-••••</td><td><span className={`il-badge ${c.status}`}>{c.status}</span></td><td>{fmt(c.createdAt)}</td><td>{fmt(c.expiresAt)}</td>
              <td>{c.usedBy?.length ? c.usedBy.map((u) => u.user?.name || "—").join(", ") : "—"}</td>
              <td>{c.status === "active" && <div className="il-btns"><button className="il-danger" onClick={() => setRevoking(c)}>Revoke</button></div>}</td></tr>)}
          </tbody></table></div>}
      </section>
    </section>
    {revoking && <ConfirmDialog title="Revoke registration code" onClose={() => { if (!revokeBusy) setRevoking(null); }} busy={revokeBusy}>
      <div className="cd-warn">This unused code ({revoking.codePrefix}-••••, expires {fmt(revoking.expiresAt)}) will stop working immediately.</div>
      <div className="cd-actions"><button className="cd-btn" onClick={() => setRevoking(null)} disabled={revokeBusy}>Cancel</button><button className="cd-btn cd-danger" onClick={confirmRevoke} disabled={revokeBusy}>{revokeBusy ? "Revoking…" : "Revoke code"}</button></div>
    </ConfirmDialog>}
  </main>;
}
